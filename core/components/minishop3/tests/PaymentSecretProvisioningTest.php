<?php

/**
 * #930: a fresh install and an upgraded site must both get a random payment
 * secret, so getOrderHash() never falls back to site_id.
 *
 * Run: php tests/PaymentSecretProvisioningTest.php
 */

declare(strict_types=1);

$fail = static function (string $message): never {
    fwrite(STDERR, "FAIL: {$message}\n");
    exit(1);
};

$root = dirname(__DIR__, 4);
$resolverPath = $root . '/_build/resolvers/resolver_03_settings.php';
$resolver = is_readable($resolverPath) ? file_get_contents($resolverPath) : false;
if ($resolver === false) {
    $fail("Unable to read {$resolverPath}");
}

foreach (['ms3_payment_secret', 'bin2hex(random_bytes(32))', 'setOption(', 'ACTION_INSTALL', 'ACTION_UPGRADE'] as $needle) {
    if (!str_contains($resolver, $needle)) {
        $fail("resolver_03_settings.php must provision the payment secret: missing {$needle} (#930)");
    }
}

$settings = require $root . '/_build/elements/settings.php';
if (!is_array($settings) || ($settings['ms3_payment_secret']['value'] ?? null) !== '') {
    $fail('Installer default for ms3_payment_secret must stay empty and be generated by the resolver (#930)');
}

foreach (['ru', 'en'] as $language) {
    $lexiconPath = $root . "/core/components/minishop3/lexicon/{$language}/setting.inc.php";
    $lexicon = is_readable($lexiconPath) ? file_get_contents($lexiconPath) : false;
    if ($lexicon === false) {
        $fail("Unable to read {$lexiconPath}");
    }
    if (!str_contains($lexicon, 'setting_ms3_payment_secret_desc')) {
        $fail("{$language} lexicon missing ms3_payment_secret description (#930)");
    }
    $generatedWord = $language === 'ru' ? 'случайным' : 'random';
    if (!str_contains($lexicon, 'site_id') || !str_contains($lexicon, $generatedWord)) {
        $fail("{$language} payment secret description must explain auto-generation and forbid site_id (#930)");
    }
}

fwrite(STDOUT, "OK PaymentSecretProvisioningTest (#930)\n");
exit(0);
